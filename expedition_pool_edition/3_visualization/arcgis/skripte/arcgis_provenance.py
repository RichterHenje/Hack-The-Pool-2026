"""Render the provenance of the ArcGIS demo map from one source file.

    uv run python -m scripts.arcgis_provenance

Reads scripts/arcgis/ke_sources.json (texts with placeholders), the newest
scripts/arcgis/provenance_counts_*.json (live layer counts, from ke_provenance_counts.js),
the team's files at the pinned commit and our check summaries. Writes
scripts/arcgis/ke_metadata_payload.json (item texts for ke_metadata.js) and
docs/21_data_provenance.md. An unresolved placeholder is an error, never an empty string.
"""

from __future__ import annotations

import html
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ARC = ROOT / "scripts" / "arcgis"
TEAM = ROOT / "reference" / "team-khm" / "Kriegsmarine" / "normalization" / "json"
HOEFER = ROOT / "analysis" / "ke_research" / "hoefer_link"

# layer id in the source file -> row in the counts file (photos: one item, two map layers)
COUNT_ROW = {"KE1893_photos_all": "KE1893_photos_dated"}
BASEMAP_CREDIT = "Basemap: Kenneth Townsend, NASA, Natural Earth, John Nelson (Esri)"
SHORT = {
    "diary": "Franz Ferdinand, Tagebuch 1895 (Internet Archive)",
    "hoefer": "Höfer (ed.) 2010",
    "weltmuseum": "Weltmuseum Wien",
    "europeana": "Europeana",
    "kulturpool": "Kulturpool",
    "anno": "ANNO/ÖNB",
    "geonames": "GeoNames",
    "wikidata": "Wikidata",
    "team": "KHM team, Hack the Pool 2026",
}


def _rights(s: dict, esc: bool = True) -> str:
    """' (rights)' when the source states its rights, else nothing."""
    r = s.get("rights")
    return f" ({html.escape(r) if esc else r})" if r else ""


def load_json(p: Path):
    return json.loads(p.read_text(encoding="utf-8"))


def newest_counts() -> Path:
    files = sorted(ARC.glob("provenance_counts_*.json"))
    if not files:
        raise FileNotFoundError("no provenance_counts_*.json; run ke_provenance_counts.js first")
    return files[-1]


def team_numbers(team_dir: Path, placed: int) -> dict:
    days = load_json(team_dir / "tagebuch_tage.json")["days"]
    photos = load_json(team_dir / "bilder.json")
    return {"diary_days": len(days), "photos": len(photos), "photos_unplaced": len(photos) - placed}


class _Keys(dict):
    """str.format turns `[1]` into the int 1; the counts file has string keys."""

    def __missing__(self, key):
        if isinstance(key, int) and str(key) in self:
            return self[str(key)]
        raise KeyError(key)


def _wrap(x):
    return _Keys({k: _wrap(v) for k, v in x.items()}) if isinstance(x, dict) else x


def fill(text: str, **ctx) -> str:
    out = text.format(**{k: _wrap(v) for k, v in ctx.items()})
    if re.search(r"\{[a-z]\[", out):
        raise KeyError(f"unresolved placeholder in: {out}")
    return out


def render(src: dict, counts: dict, team: dict, spine: dict, photo_check: dict) -> tuple[dict, str]:
    pc = spine["place_check"]
    a = {"agree": pc["agree"], "disagree": pc["disagree"], "compared": sum(pc.values())}
    run = counts["run_utc"][:10]
    sources = src["sources"]
    payload = {"run_utc": counts["run_utc"], "items": {}, "map": {}}
    md = [
        "# 21 · Data provenance of the ArcGIS demo map",
        "",
        (
            f"Generated by `scripts/arcgis_provenance.py` from `scripts/arcgis/ke_sources.json`; counts from the live layers "
            f"({counts['run_utc']}), team data at commit {src['team_commit']}. Do not edit by hand."
        ),
        "",
        "## Status words",
        "",
    ]
    md += [f"- **{w}**: {d}" for w, d in src["status_legend"]]
    for lid, lay in src["layers"].items():
        row = counts["layers"][COUNT_ROW.get(lid, lid)]
        ctx = {"c": row, "t": team, "a": a, "p": photo_check}
        what = fill(lay["what"], **ctx)
        origin = [fill(x, **ctx) for x in lay["origin"]]
        checks = [fill(x, **ctx) for x in lay["checks"]] or ["No check by a person yet."]
        for k in lay["sources"]:
            if k not in sources:
                raise KeyError(f"{lid}: unknown source {k}")
        e = html.escape
        desc = (
            f"<p><b>{e(lay['title'])}.</b> {e(what)}</p>"
            f"<p><b>Status:</b> {e(lay['status'])}.</p>"
            "<p><b>How it was made</b></p><ul>"
            + "".join(f"<li>{e(x)}</li>" for x in origin)
            + "</ul>"
            "<p><b>Checks</b></p><ul>" + "".join(f"<li>{e(x)}</li>" for x in checks) + "</ul>"
            "<p><b>Sources</b></p><ul>"
            + "".join(
                f"<li>{e(sources[k]['cite'])} {e(sources[k]['where'])} "
                f'<a href="{e(sources[k]["url"])}" target="_blank">{e(sources[k]["url"])}</a>{_rights(sources[k])}</li>'
                for k in lay["sources"]
            )
            + "</ul>"
            f"<p><i>Counted on the live layer {run}; {e(lay.get('data_note', 'team data commit ' + src['team_commit']))}.</i></p>"
        )
        payload["items"][row["item"]] = {
            "layer": lid,
            "snippet": f"{lay['title']}: {what} Status: {lay['status']}."[:2048],
            "description": desc,
            "accessInformation": "; ".join(SHORT[k] for k in lay["sources"]),
            "licenseInfo": "<ul>"
            + "".join(
                f"<li>{e(SHORT[k])}: {e(sources[k]['rights'])}</li>"
                for k in lay["sources"]
                if sources[k].get("rights")
            )
            + "</ul>",
        }
        md += [
            "",
            f"## {lay['title']} (`{lid}`)",
            "",
            what,
            "",
            f"**Status:** {lay['status']}.",
            "",
            "How it was made:",
            "",
        ]
        md += [f"- {x}" for x in origin] + ["", "Checks:", ""] + [f"- {x}" for x in checks]
        md += [
            "",
            "Sources: " + "; ".join(SHORT[k] for k in lay["sources"]) + ".",
            "",
            f"Data: {lay.get('data_note', src['team_commit'])}.",
        ]
    # pop-up footer per map layer (photos: one item, two map layers); no braces, ArcGIS reads {x} as a field
    payload["popup_footers"] = {}
    map_layers = {lid: lid for lid in src["layers"]} | src.get("popup_layers", {})
    for map_id, lid in map_layers.items():
        if lid == "KE1893_photos_all" and map_id == lid:
            continue
        f = src["layers"][lid]["footer_de"]
        foot = (
            '<p style="font-size:11px;">'
            f"<b>Quelle:</b> {html.escape(f['quelle'])}.<br/><b>Status:</b> {html.escape(f['status'])}.<br/>"
            f"<b>Rechte:</b> {html.escape(f['rechte'])}.<br/>Mehr: Beschreibung der Ebene (Details).</p>"
        )
        if "{" in foot or "}" in foot:
            raise ValueError(f"{map_id}: braces in footer")
        payload["popup_footers"][map_id] = foot
    m = src["map"]
    bib = sorted(sources)
    e = html.escape
    payload["map"] = {
        "snippet": "Demo for Hack the Pool 2026: the voyage of SMS Kaiserin Elisabeth 1892–93 with Franz Ferdinand's diary, hunts, collection, press and photographs; every layer states its source, method and check status.",
        "description": (
            f"<p>{e(m['intro'])}</p>"
            "<p><b>How to read the status</b></p><ul>"
            + "".join(f"<li><b>{e(w)}</b>: {e(d)}</li>" for w, d in src["status_legend"])
            + "</ul><p><b>Layers</b></p><ul>"
            + "".join(
                f"<li><b>{e(lay['title'])}</b>: {e(lay['status'])}</li>"
                for lay in src["layers"].values()
            )
            + "</ul><p><b>Sources</b></p><ul>"
            + "".join(
                f'<li>{e(sources[k]["cite"])} <a href="{e(sources[k]["url"])}" target="_blank">{e(sources[k]["url"])}</a>{_rights(sources[k])}</li>'
                for k in bib
            )
            + f"</ul><p><i>{e(fill(m['counted'], run=run))}</i> {e(BASEMAP_CREDIT)}, Vintage Shaded Relief.</p>"
        ),
        "accessInformation": "; ".join(SHORT[k] for k in bib) + "; " + BASEMAP_CREDIT,
        "licenseInfo": "<p>Shared publicly on 28 October 2026 (owner decision); images without a checked licence are marked “Lizenz nicht geprüft”. Rights per source:</p><ul>"
        + "".join(
            f"<li>{e(SHORT[k])}: {e(sources[k]['rights'])}</li>"
            for k in bib
            if sources[k].get("rights")
        )
        + "</ul>",
    }
    md += ["", "## Sources", ""]
    md += [
        f"- {sources[k]['cite']} {sources[k]['where']} <{sources[k]['url']}>{_rights(sources[k], esc=False)}"
        for k in bib
    ]
    return payload, "\n".join(md) + "\n"


def main() -> None:
    src = load_json(ARC / "ke_sources.json")
    counts = load_json(newest_counts())
    placed = counts["layers"]["KE1893_photos_dated"]["all_rows"]
    payload, md = render(
        src,
        counts,
        team_numbers(TEAM, placed),
        load_json(HOEFER / "compare_summary.json"),
        load_json(HOEFER / "photo_route_summary.json"),
    )
    (ARC / "ke_metadata_payload.json").write_text(
        json.dumps(payload, ensure_ascii=False, indent=1), encoding="utf-8"
    )
    (ROOT / "docs" / "21_data_provenance.md").write_text(md, encoding="utf-8")
    print(f"-> {len(payload['items'])} layer items + map; docs/21_data_provenance.md")


if __name__ == "__main__":
    main()
